package org.teavm.visualizer.fixture;

/**
 * Recursive factorial used as the browser IR-backend demo fixture.
 * Calling factorial(4) produces a call-stack depth of 4 that makes
 * the step-by-step trace visually interesting.
 */
public final class RecursiveFactorial {
    private RecursiveFactorial() {
    }

    public static int factorial(int n) {
        if (n <= 1) {
            return 1;
        }
        return n * factorial(n - 1);
    }

    public static void main(String[] args) {
        System.out.println(factorial(4));
    }
}
